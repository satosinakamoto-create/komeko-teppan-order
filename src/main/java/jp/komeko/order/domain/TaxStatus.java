package jp.komeko.order.domain;

/**
 * 自分の店が、消費税を納める立場かどうか。
 *
 * <h2>なぜ持つのか</h2>
 *
 * <p>税理士の画面が出す「控除できる税額」は、<b>課税事業者にしか意味がありません</b>。
 * 免税事業者は消費税の申告をしないので、仕入税額控除もしません。
 * そこを持っていないと、免税の店にも控除額が並び、
 * <b>数字は出るのに意味が無い画面</b>になります。
 *
 * <h2>「登録番号があるか」とは別の事実です</h2>
 *
 * <p>ひとつの真偽値では足りません。実際にある組み合わせが表せなくなります。
 *
 * <table border="1">
 *   <caption>立場と登録番号の組み合わせ</caption>
 *   <tr><th>立場</th><th>T 番号</th><th>意味</th></tr>
 *   <tr><td>{@link #TAXABLE}</td><td>あり</td>
 *       <td>適格請求書発行事業者。いちばん多い形</td></tr>
 *   <tr><td>{@link #TAXABLE}</td><td>なし</td>
 *       <td>納めるが、こちらが出す領収書では相手が控除できない</td></tr>
 *   <tr><td>{@link #EXEMPT}</td><td>なし</td>
 *       <td>免税事業者。納めない</td></tr>
 *   <tr><td>{@link #EXEMPT}</td><td>あり</td>
 *       <td><b>あり得ない。</b>登録すると課税事業者になるため（画面で弾く）</td></tr>
 * </table>
 *
 * <h2>{@link #UNSET} を既定にしている理由</h2>
 *
 * <p>免税を既定にすると、まだ何も設定していない店に
 * 「うちは消費税を納めなくてよい」と表示されます。<b>これは嘘です。</b>
 * しかも納税に関わる嘘なので、気づかれないまま確定申告まで行くと実害になります。
 *
 * <p>このアプリが「記録していません」を 0 円と書かないのと同じ考え方で、
 * 未設定は未設定のまま持ち、画面には「設定してください」と出します。
 *
 * <h2>判断そのものはこのアプリではしません</h2>
 *
 * <p>課税か免税かは、基準期間の課税売上高やインボイスの登録で決まります。
 * その判定を売上データから自動で出すことはしません。
 * <b>顧問税理士に確認して、人が選んで入力する</b>ものです。
 * 自動で決めると、変わった年に誰も気づけません。
 */
public enum TaxStatus {

    /** まだ設定していない。既定値。画面には「設定してください」と出す。 */
    UNSET("未設定"),

    /** 免税事業者。消費税を納めない（仕入税額控除もしない）。 */
    EXEMPT("免税事業者"),

    /** 課税事業者。消費税を納める。 */
    TAXABLE("課税事業者");

    private final String label;

    TaxStatus(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    /** 消費税の申告をする立場か（＝控除の話に意味があるか）。 */
    public boolean filesTaxReturn() {
        return this == TAXABLE;
    }

    /** 設定が済んでいるか。未設定のあいだは画面で促す。 */
    public boolean isDecided() {
        return this != UNSET;
    }
}
