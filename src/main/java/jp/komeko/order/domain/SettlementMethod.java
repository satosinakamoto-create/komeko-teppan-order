package jp.komeko.order.domain;

/**
 * お客さまがレジで支払った手段。
 *
 * <h2>なぜ記録するのか</h2>
 *
 * <p>閉店後のレジ締めで<b>現金が合っているか確かめるため</b>です。
 *
 * <p>これが無いと、売上画面は「今日 ¥183,200」としか言えません。
 * うちカードがいくらか分からないので、金庫を数えても
 * <b>あるべき現金の額が出せません。</b>¥63,200 出てきたとして、
 * それが正しいのか ¥5,000 足りないのか、判断する材料がない。
 *
 * <p>カードは月末締め・翌月払いで入金の時期も違うので、
 * その意味でも分かれている必要があります。
 *
 * <h2>なぜ 2 つだけなのか</h2>
 *
 * <p>店主が<b>「現金かカードのどちらか。混ぜない」</b>と決めたためです
 * （2026-09-05）。一部カード・一部現金の分割を作らないので、
 * 1 伝票に 1 つで足り、金額を持つ必要がありません。
 *
 * <p><b>電子マネー・QR 決済（PayPay など）は入れていません。</b>
 * いま「カード」で受けると、クレジット端末の当日合計と突き合わせたときに
 * 合わなくなります（入金のサイクルが別なので）。
 * 実際に受けているなら値を 1 つ足してください。
 * status 列は varchar なので、<b>足しても既存データは動きません</b>
 * （enum 列の罠は 2026-09-05 に全 12 列で塞いであります）。
 *
 * <h2>在庫側の {@code PaymentMethod} とは別物</h2>
 *
 * <p>あちらは<b>店が仕入先に払う</b>ときの手段で、口座振替や振込を含みます。
 * こちらは<b>お客さまが店に払う</b>ときの手段。
 * 同じ名前にすると売上画面のように両方を扱うクラスで衝突するので、分けてあります。
 */
public enum SettlementMethod {

    CASH("現金"),
    CARD("カード");

    private final String label;

    SettlementMethod(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }
}
