package jp.komeko.order.domain;

/**
 * 伝票（来店）の状態。
 *
 * <pre>
 *   OPEN    ご案内中。追加注文を受け付ける。
 *     ↓  「お会計おねがいします」（お客さま）／「お会計」（ホール）
 *   CLOSING お会計待ち。レジへ移動中。追加注文は受け付けない。
 *     ↓  レジで締める            ↑ 「注文を再開する」で OPEN へ戻せる
 *   CLOSED  会計済み。金額が確定し、以後は変更できない。
 * </pre>
 *
 * <h2>なぜ CLOSING を挟むのか（2026-09-05 追加）</h2>
 *
 * <p>金額を出したあとに注文が入る、という事故を<b>起きなくする</b>ためです。
 *
 * <p>それまでは「注文の確定」と「会計の締め」が同時に走らないよう
 * 行ロックで直列化していました。動いてはいましたが、
 * <b>0.1 秒の勝負を裏で黙って捌く</b>形なので、
 * 負けた側のお客さまには理由の分からないエラーが出ます。
 *
 * <p>実際に起きるのは店員どうしの衝突ではなく、<b>お客さまと店員</b>です。
 * 帰り際に「最後にレモンサワー 1 杯」と押した瞬間に、
 * 店員がレジで締めボタンを押す。1 秒ずれていれば十分成立します。
 * しかも止めないと<b>厨房が焼き始めます</b>。金額のズレは店側で直せますが、
 * 作ってしまった料理は戻せません。
 *
 * <p>CLOSING を挟むと、この間は誰も注文できません。
 * 4 人組の 1 人が「お会計おねがいします」を押せば、
 * 残り 3 人の画面でも注文が止まります。
 * <b>競合が起きないのではなく、競合という状態が存在しなくなります。</b>
 * そして「お会計待ち」はホール画面に表示されるので、
 * ロックと違って<b>人から見えます</b>。
 *
 * <p>ロックは残してあります。CLOSING へ移すこと自体も
 * 「読んで、確かめて、書く」なので直列化が要るためです。
 */
public enum SessionStatus {

    OPEN("ご案内中"),

    /**
     * お会計待ち。追加注文は受け付けないが、まだ金額は確定していない。
     *
     * <p>「やっぱりもう一杯」と言われたら、ホール画面から OPEN に戻せます
     * （新しい伝票を作るのではないので、テーブルチャージが二重になりません）。
     */
    CLOSING("お会計待ち"),

    CLOSED("会計済み");

    private final String label;

    SessionStatus(String label) {
        this.label = label;
    }

    public String getLabel() {
        return label;
    }

    public boolean isOpen() {
        return this == OPEN;
    }

    /**
     * まだ会計が済んでいない（卓が使われている）か。
     *
     * <p>お会計待ちの卓も「在席」です。席は空いていないし、
     * 金額もまだ確定していません。ホール画面の在席一覧や空席判定には
     * {@link #isOpen()} ではなくこちらを使ってください。
     */
    public boolean isActive() {
        return this == OPEN || this == CLOSING;
    }

    /** 追加注文を受け付けられるか。お会計待ちは受け付けません。 */
    public boolean acceptsOrders() {
        return this == OPEN;
    }
}
