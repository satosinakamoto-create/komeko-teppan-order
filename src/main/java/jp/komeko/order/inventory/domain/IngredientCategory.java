package jp.komeko.order.inventory.domain;

/**
 * 食材の分類。「野菜」「肉」といった、探すときのまとまり。
 *
 * <p><b>何のためにあるか</b><br>
 * 食材が 30 も 50 も並ぶと、名前を思い出せない食材は探せません。
 * 「たしか魚のなにか」までは覚えているので、そこから絞れるようにします。
 * 設計 現04 の「カテゴリーから検索」がこれです。
 *
 * <p><b>なぜ表ではなく決め打ちなのか</b><br>
 * 商品のカテゴリ（{@code Category}）は店主が並べ替えたり増やしたりするので表ですが、
 * 食材の分類は「野菜」「肉」のように業種が変わらないかぎり動きません。
 * 表にすると管理画面・並び順・削除したときの扱いまで要るので、
 * <b>足りなくなったらここに 1 行足す</b>ほうが軽い、と判断しています。
 *
 * <p><b>すでに使われている値の意味を変えないこと。</b>
 * 名前（enum の識別子）を変えると、DB に入っている文字列と対応しなくなり、
 * その食材の分類が読めなくなります（{@link IngredientUnit} と同じ約束）。
 *
 * <p><b>未分類は null で表します。</b>
 * 「その他」を既定にすると、分類し忘れた食材と、本当にその他な食材が
 * 同じ棚に混ざります。null なら「まだ決めていない」と区別できます。
 */
public enum IngredientCategory {

    /** キャベツ・青ねぎなど。 */
    VEGETABLE("野菜"),

    /** 豚バラ・牛すじなど。 */
    MEAT("肉"),

    /** たこ・いか・ホタテなど。 */
    SEAFOOD("魚介"),

    /** 米粉・そば・天かすなど、粉ものの土台になるもの。 */
    FLOUR("粉・麺"),

    /** 卵・チーズ・牛乳。 */
    EGG_DAIRY("卵・乳製品"),

    /** ソース・マヨ・油・だしなど。 */
    SEASONING("調味料・ソース"),

    /** ビール・酎ハイ・ソフトドリンク。 */
    DRINK("飲料・酒"),

    /** 割り箸・おしぼり・容器など、口に入らないもの。 */
    SUPPLIES("消耗品"),

    /** 上のどれでもないもの。分類し忘れ（null）とは区別する。 */
    OTHER("その他");

    private final String label;

    IngredientCategory(String label) {
        this.label = label;
    }

    /** 画面に出す名前。 */
    public String getLabel() {
        return label;
    }
}
