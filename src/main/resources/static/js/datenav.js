/* ============================================================================
   日付・月の帯（.datenav）— 選んだら、その場で表示する
   ============================================================================
   2026-09-18 に足しました。店主の指摘はこうです。

     「選択されてんだから、そこは自動で表示しろよ。
       キーボードで打てなくすりゃいいじゃん、カレンダーがあるんだから」

   ■ なぜボタンが要っていたのか

   <input type="date"> は値を入れるだけの部品です。カレンダーで 9月18日 を
   選んでも、ブラウザは欄に文字を入れるだけで、サーバーには何も送りません。
   送るには submit が要ります。だから「この日を表示」ボタンが並んでいました。

   ■ なぜ自動送信をためらっていたのか

   打っている途中で飛ばされるからです。

       2026/09/18 と打とうとすると…
         2 0 2 6 0 9 1 8
                   ↑ ここで「2026/09/01」が完成したとみなされ、一度送信される

   日付の欄は、打ち終わる前に「完成した日付」に見える瞬間があります。

   ■ 打てなくすれば起きない

   カレンダーから選ぶ道が残るので、打てなくても操作はできます。
   文字キーだけを止め、Tab・Esc・矢印は通します。そうしないと
   キーボードだけで操作している人がカレンダーを開けなくなります。

   ■ JavaScript が動かなくても壊れないこと

   スタッフ側は素の HTML で動かす決まりですが（CLAUDE.md）、
   送信は HTML だけではどうやっても起こせません。そのかわり、
   ボタンは HTML から消さずに CSS で隠してあります。

       JS が動く     … ボタンは隠れていて、選んだ瞬間に切り替わる
       JS が動かない … レイアウトの <noscript> がボタンを出すので、押せば今までどおり

   消してしまうと後者が成立しません。隠すだけ、が要点です。
   ============================================================================ */
(function () {
  'use strict';

  var FIELD = '.datenav input[type="date"], .datenav input[type="month"]';

  /* 帯の中の日付・月の欄かどうか。
     ここで拾い損ねると、他の画面の入力欄まで止めてしまうので範囲を絞る。 */
  function isDateField(el) {
    return !!(el && el.matches && el.matches(FIELD));
  }

  /* --- 選んだら送る ------------------------------------------------------
     イベントを document で受けているのは、帯が画面ごとに別のテンプレートに
     あるためです。1 か所で受ければ、帯を増やしても書き足す所がありません。 */
  document.addEventListener('change', function (e) {
    if (!isDateField(e.target)) return;

    var form = e.target.form;
    /* 値が空のときは送らない。欄を消しただけで今日に飛ぶと驚くので。 */
    if (!form || !e.target.value) return;

    /* requestSubmit は <button type="submit"> を押したのと同じ扱いで、
       入力の検査も走ります。古いブラウザ向けに submit も残しています。 */
    if (form.requestSubmit) {
      form.requestSubmit();
    } else {
      form.submit();
    }
  });

  /* --- 打たせない --------------------------------------------------------
     key.length === 1 は「文字が 1 つ入るキー」つまり数字や記号です。
     Tab・Escape・ArrowUp・Backspace は名前が 2 文字以上なので通ります。
     全部止めると、キーボードだけで操作している人が
     カレンダーを開くことすらできなくなります。 */
  document.addEventListener('keydown', function (e) {
    if (!isDateField(e.target)) return;
    if (e.key && e.key.length === 1) e.preventDefault();
  });
})();
