--  設計 08-2 商品を追加（315:1983）／08-3（318:2012）で、掲載の状態が
--  3 つになった。
--
--      編集中   … まだ作りかけ。お客さまには出さない
--      掲載中   … メニューに並ぶ
--      掲載停止 … 一度出したものを引っ込めた
--
--  ★ なぜ visible の false で兼ねられないか
--    「掲載停止」と「編集中」は、同じ<b>出していない</b>でも意味が違う。
--    掲載停止は中身がそろっていて、季節などの理由でいま隠しているだけ。
--    編集中は価格が空かもしれない、作りかけ。
--    真偽値 1 つで両方を表すと、商品一覧で作りかけと季節外れが同じ棚に並び、
--    店主が探しているほう（作りかけ）を毎回全部見て探すことになる。
--
--  ★ DEFAULT FALSE を必ず書く（V9 に同じ注意がある）
--    既存の商品はすべて作り終わったものなので、正しい既定値は false。
--    NOT NULL の列を DEFAULT 無しで足すと、既存の行を埋められず失敗する。
--    dev / demo は ddl-auto: update で足すので、
--    エンティティ側にも columnDefinition で同じ既定値を書いてある。
--
--  ★ 既存の行に true を入れないこと
--    true にすると、いま出ている商品が全部お客さまのメニューから消える。
--    MenuItem#isOrderable が draft を見て落とすため。
-- ----------------------------------------------------------------------------
ALTER TABLE menu_item ADD COLUMN draft BOOLEAN DEFAULT FALSE NOT NULL;
