-- ============================================================================
--  設計「暗03 サービス」のタイルと、伝票の「お会計をお願いする」ボタン。
--
--  ★ 持っていく物はこの表に入らない
--    お水・おしぼり・取り皿・灰皿・塩コショウ・領収書は
--    ¥0 の商品として注文（orders）に流し、厨房ボードに出す。
--    あちらには「出したか」という進行があり、注文の状態遷移がそのまま使える。
--
--    ここに入るのは物が伴わない呼びかけ（スタッフを呼ぶ／お会計をお願いする）だけ。
--    金額も個数も無いので、注文に混ぜると売上と客単価の意味が濁る。
--    2026-09-05 に店主と決めた振り分け。
--
--  ★ 卓ではなく伝票に紐づける
--    卓に紐づけると、会計して次のお客さまが座ったあとも
--    同じ卓の呼び出しとして残り、誰が呼んだのか分からなくなる。
--
--  ★ 対応済みも消さずに残す
--    「何回呼ばれたか」「どれくらい待たせたか」は、あとから店の動きを
--    見直すときの材料になる。消すと、忙しかった日ほど記録が残らない。
-- ----------------------------------------------------------------------------

CREATE TABLE service_call (
    id            BIGSERIAL    PRIMARY KEY,
    session_id    BIGINT       NOT NULL REFERENCES table_session (id),
    type          VARCHAR(20)  NOT NULL,
    business_date DATE         NOT NULL,
    created_at    TIMESTAMP    NOT NULL,
    handled_at    TIMESTAMP,
    handled_by    VARCHAR(40)
);

-- ホール画面は「未対応を古い順に」しか読まない。
-- handled_at IS NULL の行だけを対象にした部分インデックスにすると、
-- 対応済みが積み上がっても検索の重さが変わらない。
CREATE INDEX idx_service_call_pending
    ON service_call (created_at)
    WHERE handled_at IS NULL;
