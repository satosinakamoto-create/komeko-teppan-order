-- ============================================================================
--  V14 : 食材の分類（野菜・肉・魚介…）
-- ============================================================================
--  設計 現04 食材・在庫（441:2715）に「カテゴリーから検索」が足された。
--  食材が 30 も 50 も並ぶと、名前を思い出せないものは探せない。
--  「たしか魚のなにか」までは覚えているので、そこから絞れるようにする。
--
--  ★ NULL を許す（DEFAULT を置かない）
--    既存の食材はどれも分類されていない。ここで 'OTHER' で埋めると、
--    「分類し忘れ」と「本当にその他」が同じ棚に混ざって、あとから
--    片付けようがなくなる。NULL のままにして画面では「未分類」と出し、
--    店主が手を付けるべき食材が見えるようにしておく。
--
--  ★ 表ではなく列にした理由
--    商品のカテゴリ（category テーブル）は店主が増やしたり並べ替えたりするが、
--    食材の分類は業種が変わらないかぎり動かない。表にすると管理画面・並び順・
--    削除したときの扱いまで要る。足りなくなったら
--    IngredientCategory に 1 行足すほうが軽い、と判断した。
--    あとから表に変えるときも、この列を外部キーに置き換えるだけで済む。
--
--  ★ 値は enum の名前をそのまま入れる（VEGETABLE / MEAT / …）
--    IngredientCategory の識別子を変えると、ここに入っている文字列と
--    対応しなくなって分類が読めなくなる。名前は変えないこと。
-- ----------------------------------------------------------------------------
ALTER TABLE ingredient ADD COLUMN category VARCHAR(20);
