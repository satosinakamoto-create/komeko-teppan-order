-- ----------------------------------------------------------------------------
--  税理士の確認記録
-- ----------------------------------------------------------------------------
--  店の「紙と見比べました」（equivalence_checked_at）とは別物。
--  あちらは電子帳簿保存法の同等確認で、店の人がやる作業。
--  こちらは税理士が帳簿として見たという記録で、いわば第二の目。
--
--  誰がいつ見たかを残すのは、あとから「この仕入れは確認済みか」を
--  人の記憶に頼らず言えるようにするため。
-- ----------------------------------------------------------------------------
ALTER TABLE purchase ADD COLUMN accountant_checked_at TIMESTAMP;
ALTER TABLE purchase ADD COLUMN accountant_checked_by BIGINT;
ALTER TABLE purchase ADD COLUMN accountant_note VARCHAR(300);


-- ----------------------------------------------------------------------------
--  仕訳の対応表（費目 → 勘定科目・税区分）
-- ----------------------------------------------------------------------------
--  会計ソフトに取り込める CSV を作るには、店の言葉（食材・消耗品）を
--  会計の言葉（仕入高・消耗品費）に翻訳する必要がある。
--
--  ★ 税区分は「カテゴリ×税率×控除率」の3つで決まる。
--    同じ食材（8%）でも、インボイスがあれば全額控除、無ければ経過措置80%で、
--    会計ソフト上はまったく別の税区分になる。2キーでは足りない。
--
--  ★ 文字列は事務所ごとに違う。
--    弥生は「その事務所に登録されている税区分名と完全一致」でないと弾かれ、
--    freee と MF はまた別の文字列を使う。だからコードに焼かず、
--    画面から直せる行として持つ。ここを間違えると取り込みが丸ごと失敗する。
-- ----------------------------------------------------------------------------
CREATE TABLE journal_rule (
    id                     BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category               VARCHAR(20)  NOT NULL,
    tax_rate_percent       INTEGER      NOT NULL,
    deduction_rate_percent INTEGER      NOT NULL,
    account_name           VARCHAR(24)  NOT NULL,
    tax_class_name         VARCHAR(32)  NOT NULL,
    note                   VARCHAR(200),

    CONSTRAINT uk_journal_rule UNIQUE (category, tax_rate_percent, deduction_rate_percent)
);

CREATE INDEX idx_journal_rule_lookup ON journal_rule (category, tax_rate_percent, deduction_rate_percent);
