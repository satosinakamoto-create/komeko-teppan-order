-- ============================================================================
--  V17 : 食材の分類（V14）をやめる
-- ============================================================================
--  店主の「分類いるこれ？」から全参照をあたった結果、この列を読んでいるのは
--  画面の絞り込みと表示だけで、計算にはいっさい使われていなかった。
--
--      TaxRuleService（税率）       … 0 件
--      StockService（在庫）         … 0 件
--      ConsumptionService（消費）   … 0 件
--      RecipeCost（原価）           … 0 件
--      PurchaseSummary（集計）      … 0 件
--
--  分類を 1 件も付けなくても、原価率も在庫も税額もまったく同じ数字が出る。
--  それなのに食材一覧は「分類が決まっていない食材が N 件あります →
--  まとめて分類する」と催促していた。何も産まない作業を催促していたことになる。
--
--  ★ もう 1 つの理由が「カテゴリー」という語の衝突
--    品切れ・残数の「カテゴリーから検索」は商品カテゴリ（お品書きの 14 分類）、
--    食材・在庫の「カテゴリーから検索」は食材の分類で、同じサイドバーの中で
--    同じ文言が別のものを指していた。コードでも categoryGroups という同じ名前が
--    両方で使われていて、作った本人が読み違えた。店員が読み違えないはずがない。
--
--  ★ 消えるデータについて
--    この列に入っているのは「野菜」「肉」といった探すための札だけで、
--    金額・数量・日付はいっさい入っていない。会計の証跡ではないので、
--    列ごと落として差し支えない（仕入れ・棚卸し・レシピは 1 行も触らない）。
--
--  ★ フィールドと列は必ず同時に消すこと
--    本番は ddl-auto: validate。Ingredient.category を消して列を残すと、
--    検証は通るが「使われない列」が残り続ける。逆に列だけ落として
--    フィールドを残すと、起動時の検証で落ちてアプリが上がらない。
--
--  ★ もし「魚のなにか」で探したくなったら
--    消したのは「手で札を貼る仕組み」。作り直すなら、レシート読取が既に
--    Claude を呼んでいるので、その JSON スキーマに 1 項目足して自動で埋める
--    ほうから検討すること。人に貼らせる画面をもう一度作らない。
-- ----------------------------------------------------------------------------
ALTER TABLE ingredient DROP COLUMN category;
