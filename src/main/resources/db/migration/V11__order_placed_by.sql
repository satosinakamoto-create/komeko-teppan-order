-- ============================================================================
--  V11 : スタッフが入れた注文の記録
-- ============================================================================
--  厨房・ホールから注文を入れられるようにするのに合わせて、列を 1 本足す。
--
--  ★ なぜ要るか
--    時価の品（国産牛ステーキなど）は、その日の仕入れを見てスタッフが
--    金額を決める。つまり<b>請求額の一部を人が決めている</b>ことになる。
--    あとで「この 6,800 円は誰が決めたのか」を確かめられないと、
--    金額の間違いも、意図的な操作も、どちらも追えない。
--
--    お客さまが自分で入れた注文は NULL のままにする。
--    そこが空であること自体が「お客さま入力」の意味になる。
--    "お客さま" のような文字列を入れると、
--    その名前のスタッフがいた場合に区別できなくなる。
--
--  ★ なぜ lastHandledBy を使い回さないのか
--    lastHandledBy は「最後に状態を進めた人」で、調理開始や提供済みのたびに
--    上書きされる。入れた人の記録に使うと、厨房が「調理中」にした瞬間に
--    消える。意味の違う 2 つを 1 本の列で持つと、片方が必ず失われる。
--
--  ★ NOT NULL にしない（DEFAULT も書かない）
--    既存の注文はすべてお客さま入力なので、正しい値は「無い」。
--    ここで DEFAULT を置くと、過去の注文に入れた覚えのない名前が付く。
--    V9 で DEFAULT を必ず書けと書いたのは NOT NULL の列の話で、
--    NULL を許す列にはあてはまらない。
--
--  長さ 40 は last_handled_by にそろえた（同じスタッフ名が入るため）。
-- ----------------------------------------------------------------------------
ALTER TABLE orders ADD COLUMN placed_by VARCHAR(40);
