-- ============================================================================
--  V8 : 同じ選択肢を複数選べるようにする（保存の形だけ）
-- ============================================================================
--  たこ焼きの「4 種類お選びください」は、いまチェックボックスなので
--  同じ味を 2 回選べない。「ソース 3 つ・ごま油 1 つ」は入力できない。
--
--  実際にそういう頼まれ方をするのかは店主に確認中。ただ、
--  <b>あとから直すと注文データの形が変わる</b>ので、保存の形だけ先に整えておく。
--  画面は一切変えていない。設定を ON にする手段も、いまは無い。
--
--  ★ なぜ「同じ行を 3 本入れる」ではなく「行に個数を持たせる」のか
--    厨房のチケットに同じ字が 3 行並ぶのを避けたい。
--    「ソース ×3」と 1 行で出したいので、個数を持つ形にする。
--    集計のたびにまとめ直す処理も要らなくなる。
--
--  ★ 既存データへの影響はゼロ
--    quantity は既定 1。いま入っている注文はすべて「1 個ずつ選んだ」ままの意味になる。
--    allow_duplicate は既定 false。いまのグループは全部これまでどおり。
--
--  ★ DEFAULT を必ず書くこと
--    データの入った DB に NOT NULL の列を足すと、既存行に何を入れるか
--    決められずに ALTER が失敗する。2026-09-05 に monthly_rent で実際に踏んだ
--    （ShopSetting.java のコメント参照）。エンティティ側の columnDefinition にも
--    同じ既定値を書いてある。
-- ----------------------------------------------------------------------------

-- 同じ選択肢を複数選べるグループか。既定は false（これまでどおり 1 回だけ）
ALTER TABLE option_group ADD COLUMN allow_duplicate BOOLEAN DEFAULT FALSE NOT NULL;

-- 注文明細のオプション 1 行あたりの個数。既定は 1
ALTER TABLE order_line_option ADD COLUMN quantity INTEGER DEFAULT 1 NOT NULL;
