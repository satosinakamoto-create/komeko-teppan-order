-- ============================================================================
--  V20 : 品ごとの段階（未調理 → 調理済み → 提供済み）
-- ============================================================================
--  厨房ボードを注文単位から品単位に作り替えるために足します。
--  店主の指摘がそのまま理由。
--    「これ一気に注文入ったら一気にその卓の料理しないといけなくなるわけじゃん。
--      でも調理は一つずつだから、どうやって提供可能のボタン分けたら良いか
--      って問題に直面してるんだよね」
--
--  orders.status（注文の状態）はそのまま残します。あちらはカートを一度に
--  確定した単位で、キャンセルや会計の判定に使っています。こちらは「焼けたか」
--  だけを見る別の軸です。
--
--  ★ cooked_at を持つ理由
--    調理済みレーンの並び順がこれで決まります。注文からの経過時間ではありません。
--    左のレーンは「何分待たせたか」、右は「焼き上がってから何分置いたか」で、
--    見ている時計が違います。右に注文時刻を持ち込むと、皿に乗ったばかりの品が
--    上に、8 分置かれた品が下に並びます。
--
--  ★ DEFAULT を必ず書く（V12・V15・V19 と同じ注意）
-- ----------------------------------------------------------------------------
ALTER TABLE order_line ADD COLUMN stage VARCHAR(20) DEFAULT 'UNCOOKED' NOT NULL;
ALTER TABLE order_line ADD COLUMN cooked_at TIMESTAMP;
ALTER TABLE order_line ADD COLUMN served_at TIMESTAMP;

-- ----------------------------------------------------------------------------
--  すでにある注文を、注文の状態から品の段階へ写す
-- ----------------------------------------------------------------------------
--  既定の UNCOOKED のままにすると、<b>提供し終えた過去の品が全部「未調理」</b>
--  として厨房ボードに並びます。営業中に流すと、焼いた覚えのない品が数十件
--  現れることになるので、ここで辻褄を合わせておきます。
--
--    COMPLETED（提供済み）・CANCELED  → SERVED（ボードから消える）
--    READY（お渡し可）                → COOKED（調理済みレーンへ）
--    RECEIVED / COOKING               → UNCOOKED（そのまま）
--
--  CANCELED を SERVED にするのは「運んだ」という意味ではなく、
--  <b>ボードに出さない</b>ためです。取り消した注文の品は
--  order_line.canceled では拾えません（V19 は注文ごとの取り消しを
--  明細へ写していないため）。ここで段階を進めて消します。
-- ----------------------------------------------------------------------------
UPDATE order_line SET stage = 'SERVED'
 WHERE order_id IN (SELECT id FROM orders WHERE status IN ('COMPLETED', 'CANCELED'));

UPDATE order_line SET stage = 'COOKED'
 WHERE order_id IN (SELECT id FROM orders WHERE status = 'READY');

-- 時刻は分からないので入れません（null のまま）。
-- 並び順に使うのは cooked_at ですが、過去の品はすでにボードから消えているか、
-- READY のぶんだけです。null は「いちばん古い」として扱います。
