-- ============================================================================
--  V10 : 自分の店の消費税の立場と、インボイスの登録番号
-- ============================================================================
--  ★ 「もらう側」はもう持っている。足りないのは「出す側」だった
--
--    仕入先の登録番号は V2 から purchase に持っています
--    （reg_number / reg_verify_status / evidence_type / deduction_rate_percent）。
--    レシートに T 番号があるかどうかで、控除できる税額が変わるからです。
--
--    ところが<b>自分の店の番号はどこにも無い</b>状態でした。
--    店舗設定にも、税理士の画面にも出てきません。
--
--  ★ なぜ 2 つに分けるのか（true / false 1 つでは足りない）
--
--    「消費税を納める立場か」と「適格請求書を出せるか」は別の事実です。
--
--      tax_status … 消費税を納めるか。免税事業者は納めない
--      invoice_registration_number … T 番号。あれば適格請求書を出せる
--
--    分けないと表せない組み合わせが実際にあります。
--    課税事業者だがインボイスには登録していない、という状態です
--    （納めるけれど、こちらが出す領収書では相手が控除できない）。
--
--    逆に「免税事業者なのに T 番号がある」はあり得ません。
--    登録すると、売上の規模にかかわらず課税事業者になるためです。
--    この組み合わせは画面で弾いています。
--
--  ★ 既定を UNSET にしている理由
--
--    false（＝免税事業者）を既定にすると、まだ何も設定していない店が
--    「うちは消費税を納めなくてよい」と表示されます。
--    これは<b>嘘です。</b>しかも納税に関わる嘘なので、気づかれないまま
--    確定申告まで行くと実害になります。
--
--    未設定は未設定として持ち、画面には「設定してください」と出します。
--    このアプリが「記録していません」を 0 円と書かないのと同じ考え方です。
--
--  ★ 免税事業者だと、税理士画面の意味が変わる
--
--    /accountant/tax は「控除できる税額」を出しますが、
--    免税事業者は消費税の申告をしないので<b>控除もしません</b>。
--    数字は出るのに意味が無い、という状態になるため、
--    課税事業者でないときは画面の上に断りを出しています。
-- ----------------------------------------------------------------------------

-- 消費税を納める立場か。UNSET / EXEMPT（免税事業者）/ TAXABLE（課税事業者）
ALTER TABLE shop_setting
    ADD COLUMN tax_status VARCHAR(20) DEFAULT 'UNSET' NOT NULL;

-- インボイスの登録番号（T + 13 桁）。持っていなければ NULL。
-- 桁数は purchase.reg_number と同じ 14。突き合わせるときに型を揃えておく
ALTER TABLE shop_setting
    ADD COLUMN invoice_registration_number VARCHAR(14);
