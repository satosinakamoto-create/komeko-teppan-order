-- ----------------------------------------------------------------------------
--  決済手段（現金 / カード）
-- ----------------------------------------------------------------------------
--  なぜ要るか: いま売上は「今日 ¥183,200」しか出せず、うちカードが
--  いくらかを持っていない。だから閉店後に金庫を数えても、
--  あるべき現金の額が出せず、合っているかどうか確かめられない。
--
--  NULL を許すのは、すでに会計済みの伝票に後から嘘を入れないため。
--  過去の伝票は「記録していない」のままにして、画面でもそう出す。
--  0 円と書くと「現金だった」という嘘になるのと同じ理屈。
--
--  混在（一部カード・一部現金）は仕様として作らない、と店主が決めた。
--  だから 1 伝票 1 手段で足りる（金額を持つ必要が無い）。
ALTER TABLE table_session ADD COLUMN payment_method VARCHAR(20);


-- ----------------------------------------------------------------------------
--  テーブルチャージを取らない人数
-- ----------------------------------------------------------------------------
--  未就学児からお通し代を取らない、常連さんにサービスする、など。
--
--  ★ なぜ「免除する/しない」の真偽値ではなく人数なのか
--    大人 4 名＋未就学児 2 名のとき、真偽値だと「全額取る」か
--    「全額取らない」しか選べない。人数なら 4 名ぶんだけ請求できる。
--    常連さんへの全額サービスも exempt = 人数と同じ値を入れれば表せるので、
--    1 本で両方を賄える。
--
--  ★ なぜ guest_count を減らす運用ではいけないのか
--    guest_count は「チャージの計算」と「売上の客数」の両方で使われている。
--    6 名を 4 名に書き換えるとチャージは正しくなるが、
--    売上の客数と客単価が壊れる。実際には 6 名ご来店しているのに。
--    列を分ければ、客数は 6 のまま、チャージだけ 4 名ぶんにできる。
ALTER TABLE table_session ADD COLUMN charge_exempt_count INTEGER DEFAULT 0 NOT NULL;
