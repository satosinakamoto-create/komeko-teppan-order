--      CLOSING で「Value not permitted」が出たら data\ を作り直すこと）
--
--  ★ DEFAULT を必ず書く
--    データの入った DB に NOT NULL の列を足すと、既存行に何を入れるか
--    決められずに ALTER が失敗する（monthly_rent で実際に踏んだ）。
