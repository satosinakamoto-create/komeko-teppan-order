--  ★ なぜ仕入れ（purchases）ではなく店舗設定に置くのか
--    家賃は「仕入れた」ものではなく、毎月同じ額が出ていく固定費。
--    PurchaseCategory（食材／飲料・酒／消耗品／光熱費／その他）に入れると
--    帳簿では雑費に混ざってしまい、税理士に渡す仕訳が狂う。
--    毎月の入力も要らない（変わらないので）から、設定として 1 つ持つ。
--
--  ★ 0 を既定値にする
--    家賃が未設定の店で 0 円と表示すると「家賃がかかっていない」という嘘になる。
--    0 のときは画面側で「記録していません」を出し続ける。
--    金額を入れて初めて、配分の実績に載る。
